• অর্ধ-তৎসম শব্দ: যেসব সংস্কৃত শব্দ কিছুটা বিকৃত হয়ে বাংলা ভাষায় এসেছে, তাদের অর্ধ-তৎসম শব্দ বলে। যেমন: জ্যোৎস্না > জোছনা; শ্রাদ্ধ > ছেরাদ্য; গৃহিণী > গিন্নি; বৈষ্ণব > বোষ্টম; কুৎসিত > কুচ্ছিত।
• তদ্ভব শব্দ: যেসব সংস্কৃত শব্দের মূল রূপ সংস্কৃত বা প্রাকৃত ভাষায় পাওয়া যায় কিন্তু কালক্রমে প্রাকৃতের মাধ্যমে পরিবর্তিত হয়ে আধুনিক বাংলায় এসেছে, তাদের তদ্ভব শব্দ বলে (একে খাঁটি বাংলা শব্দও বলা হয়)। যেমন: হস্ত > হত্থ > হাত; চর্মকার > চম্মআর > চামার; কার্য > কজ্জ > কাজ।
• দেশি শব্দ: বাংলাদেশের আদিম অধিবাসীদের (কোল, মুণ্ডা, দ্রাবিড় প্রভৃতি) ভাষা ও সংস্কৃতির যেসব শব্দ বাংলায় প্রচলিত রয়েছে, তাদের দেশি শব্দ বলে। যেমন: কুলা, গঞ্জ, চঙ্গা, টোপর, ডাব, ঢোল, পেট, কুড়ি (বিশ)।
• বিদেশি শব্দ: রাজনৈতিক, ধর্মীয়, বাণিজ্যিক ও সাংস্কৃতিক কারণে বিভিন্ন বিদেশি ভাষার যেসব শব্দ বাংলা ভাষায় স্থান করে নিয়েছে, তাদের বিদেশি শব্দ বলে।
  - আরবি শব্দ: আল্লাহ, ইসলাম, ঈমান, ওজু, কোরআন, আদালত, কানুন, কলম, উকিল।
