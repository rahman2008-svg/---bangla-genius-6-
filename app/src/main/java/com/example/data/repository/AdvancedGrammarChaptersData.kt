উচ্চারণের সময় একটি ধ্বনি অন্য ধ্বনিতে রূপান্তরিত হলে তাকে ধ্বনির পরিবর্তন বলে।

### ধ্বনির পরিবর্তনের কারণ
• উচ্চারণ সহজ করার জন্য।
• ভাষার স্বাভাবিক বিবর্তন ও আঞ্চলিক ভাষার প্রভাব।
• অন্য ভাষার প্রভাব ও দ্রুত উচ্চারণের প্রবণতা।

