## ধ্বনির পরিবর্তনের প্রধান প্রকারভেদ

### ১. ধ্বনির আগম (Addition)
শব্দে নতুন ধ্বনি যুক্ত হয়।
• **উদাহরণ:** স্কুল → ইস্কুল; স্টেশন → ইস্টেশন।

### ২. ধ্বনির লোপ (Deletion)
শব্দ থেকে কোনো ধ্বনি বাদ পড়ে।
• **উদাহরণ:** তাহার → তার; কহিল → কইল; করিয়াছি → করেছি।

### ৩. ধ্বনির আদেশ (Substitution)
একটি ধ্বনির পরিবর্তে অন্য ধ্বনি ব্যবহৃত হয়।
• **উদাহরণ:** শশী → সসি (কথ্য/আঞ্চলিক); বিষ্ণু → বিশ্নু (কথ্য)।

### ৪. ধ্বনির দ্বিত্ব (Gemination)
একই ধ্বনি পরপর দুইবার উচ্চারিত হয়।
• **উদাহরণ:** অন্ন, উল্লাস, সম্মান, অট্টালিকা।

### ৫. ধ্বনির সমীভবন (Assimilation)
পাশাপাশি দুটি ধ্বনি একে অপরের প্রভাবে মিল বা সাদৃশ্য লাভ করে।
• **উদাহরণ:** দুঃ + খ → দুঃখ; উৎ + সব → উৎসব।

### ৬. ধ্বনির বিপর্যাস (Metathesis)
ধ্বনির অবস্থান পরিবর্তিত হয়।
• **উদাহরণ:** লালন → নালল (আঞ্চলিক/কথ্য রূপে স্থানবদল)।

